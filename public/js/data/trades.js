export function findTradeByKeywords(query) {
  if (!query) return TRADES[0];
  const q = query.toLowerCase().trim();
  
  // Exact id or label
  const exact = TRADES.find(t => t.id === q || t.label.toLowerCase() === q);
  if (exact) return exact;

  // Check alias mappings first
  for (const [tradeId, keywords] of Object.entries(TRADE_ALIASES)) {
    if (keywords.some(k => q.includes(k))) {
      const match = TRADES.find(t => t.id === tradeId);
      if (match) return match;
    }
  }

  const byId = TRADES.find(t => t.id.toLowerCase().includes(q));
  if (byId) return byId;
  const byLabel = TRADES.find(t => t.label.toLowerCase().includes(q));
  if (byLabel) return byLabel;
  const byCat = TRADES.find(t => t.category.toLowerCase().includes(q));
  if (byCat) return byCat;
  const bySub = TRADES.find(t => t.subcategories.some(s => s.toLowerCase().includes(q)));
  if (bySub) return bySub;
  return TRADES[0];
}

